/**
 * The map. MapLibre GL over OpenFreeMap's Positron style (free for
 * production use, no API key; muted and light so the data layers dominate).
 *
 * VISUAL HIERARCHY — projects are the subject, crashes are context:
 *  - Projects render largest and topmost: a paper-colored casing (cuts a
 *    clean channel through the basemap) under an ink casing (holds status
 *    colors to 3:1+ contrast on light ground) under the status-color line or
 *    point itself. Placeholder lines draw dashed, placeholder points draw
 *    hollow — examples must look provisional, never mistaken for real.
 *  - Crashes render smallest and beneath projects: small dots, opacity/size
 *    receding at county-wide zoom and firming up as you zoom into a
 *    neighborhood. People walking are filled circles, people biking are
 *    rings (shape, not color, separates them); fatal crashes are larger with
 *    a dark outline. Rendered respectfully: no icons, no gamification,
 *    minimal popover copy.
 *  - Schools: small neutral squares, name on click/tap.
 *  - A quiet Henrico County outline frames all of it; every custom layer is
 *    inserted via LAYER_ORDER so the stacking above is a structural
 *    invariant, not something that depends on data-load timing.
 *
 * This component is lazy-loaded so document pages never pay for MapLibre.
 * If WebGL is unavailable the parent never mounts this — the project list
 * and detail pages work fully without a map.
 */
