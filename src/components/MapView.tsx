/**
 * Henrico County's real bounds (generated by scripts/fetch-boundary.mjs from
 * the same Census TIGERweb polygon rendered as the outline layer below — the
 * initial camera and the outline can never drift out of sync). Used for the
 * initial `fitBounds` and, padded, for `maxBounds`.
 */
const COUNTY_BOUNDS: [[number, number], [number, number]] = [
  [henricoBounds.minLng, henricoBounds.minLat],
  [henricoBounds.maxLng, henricoBounds.maxLat],
]

/** Generous pan limit: county bounds padded ~45%, enough to see Richmond and
 *  neighboring counties for orientation, not so much a visitor can wander off
 *  to another state. */
function paddedMaxBounds(): [[number, number], [number, number]] {
  const [[minLng, minLat], [maxLng, maxLat]] = COUNTY_BOUNDS
  const padLng = (maxLng - minLng) * 0.45
  const padLat = (maxLat - minLat) * 0.45
  return [
    [minLng - padLng, minLat - padLat],
    [maxLng + padLng, maxLat + padLat],
  ]
}

